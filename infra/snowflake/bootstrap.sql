-- Planwerk: one-time Snowflake setup in the browser (Snowsight worksheet, role ACCOUNTADMIN).
-- Creates the same objects as infra/terraform/snowflake. Use either this file or Terraform, not both.
-- Render it with the public keys first:  python scripts/snowflake_keys.py   (writes keys/ and
-- keys/bootstrap.rendered.sql). Paste the rendered file into a worksheet, select all, "Run all".
-- All company data loaded here is SIMULATED (fictional Nordwerk GmbH).

USE ROLE ACCOUNTADMIN;

-- Storage --------------------------------------------------------------------------------------
CREATE DATABASE IF NOT EXISTS PLANWERK DATA_RETENTION_TIME_IN_DAYS = 7
  COMMENT = 'Planwerk controlling platform - simulated data';
CREATE SCHEMA IF NOT EXISTS PLANWERK.S4_RAW       COMMENT = 'S/4HANA extracts as loaded (Parquet -> tables)';
CREATE SCHEMA IF NOT EXISTS PLANWERK.STAGING      COMMENT = 'dbt staging views';
CREATE SCHEMA IF NOT EXISTS PLANWERK.INTERMEDIATE COMMENT = 'dbt intermediate tables';
CREATE SCHEMA IF NOT EXISTS PLANWERK.CORE         COMMENT = 'Kimball dimensions and facts';
CREATE SCHEMA IF NOT EXISTS PLANWERK.CONTROLLING  COMMENT = 'Controlling marts (DB I-III, BAB, PVM, GKV)';
CREATE SCHEMA IF NOT EXISTS PLANWERK.SEMANTIC     COMMENT = 'Semantic views for SAC and the AI assistant';
CREATE SCHEMA IF NOT EXISTS PLANWERK.FORECAST     COMMENT = 'Rolling forecast and liquidity outputs';
CREATE SCHEMA IF NOT EXISTS PLANWERK.REFERENCE    COMMENT = 'Seeds: access list, DB scheme, GKV mapping';

-- Compute: XS warehouse, suspends after 60 s, hard monthly credit cap ----------------------------
CREATE RESOURCE MONITOR IF NOT EXISTS PLANWERK_MONTHLY_CAP
  WITH CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE IF NOT EXISTS PLANWERK_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  RESOURCE_MONITOR = PLANWERK_MONTHLY_CAP COMMENT = 'Planwerk (simulated Nordwerk GmbH data)';

-- Roles -----------------------------------------------------------------------------------------
CREATE ROLE IF NOT EXISTS PLANWERK_LOADER      COMMENT = 'Writes S4_RAW only';
CREATE ROLE IF NOT EXISTS PLANWERK_TRANSFORMER COMMENT = 'dbt: reads S4_RAW, owns STAGING..SEMANTIC';
CREATE ROLE IF NOT EXISTS PLANWERK_REPORTER    COMMENT = 'Controllers, SAC: read CONTROLLING and SEMANTIC';
CREATE ROLE IF NOT EXISTS PLANWERK_ASSISTANT   COMMENT = 'AI assistant: read SEMANTIC only';
GRANT ROLE PLANWERK_LOADER      TO ROLE SYSADMIN;
GRANT ROLE PLANWERK_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE PLANWERK_REPORTER    TO ROLE SYSADMIN;
GRANT ROLE PLANWERK_ASSISTANT   TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE PLANWERK_WH TO ROLE PLANWERK_LOADER;
GRANT USAGE ON WAREHOUSE PLANWERK_WH TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE ON WAREHOUSE PLANWERK_WH TO ROLE PLANWERK_REPORTER;
GRANT USAGE ON WAREHOUSE PLANWERK_WH TO ROLE PLANWERK_ASSISTANT;
GRANT USAGE ON DATABASE PLANWERK TO ROLE PLANWERK_LOADER;
GRANT USAGE ON DATABASE PLANWERK TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE ON DATABASE PLANWERK TO ROLE PLANWERK_REPORTER;
GRANT USAGE ON DATABASE PLANWERK TO ROLE PLANWERK_ASSISTANT;

-- Loader: write S4_RAW only
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA PLANWERK.S4_RAW TO ROLE PLANWERK_LOADER;

-- Transformer: read S4_RAW, build the dbt schemas, attach the row access policy
GRANT USAGE ON SCHEMA PLANWERK.S4_RAW TO ROLE PLANWERK_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA PLANWERK.S4_RAW TO ROLE PLANWERK_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PLANWERK.S4_RAW TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.STAGING      TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.INTERMEDIATE TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.CORE         TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.CONTROLLING  TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.SEMANTIC     TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.FORECAST     TO ROLE PLANWERK_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE ROW ACCESS POLICY ON SCHEMA PLANWERK.REFERENCE    TO ROLE PLANWERK_TRANSFORMER;
GRANT APPLY ROW ACCESS POLICY ON ACCOUNT TO ROLE PLANWERK_TRANSFORMER;

-- Reporter: read controlling outputs
GRANT USAGE ON SCHEMA PLANWERK.CONTROLLING TO ROLE PLANWERK_REPORTER;
GRANT USAGE ON SCHEMA PLANWERK.SEMANTIC    TO ROLE PLANWERK_REPORTER;
GRANT USAGE ON SCHEMA PLANWERK.FORECAST    TO ROLE PLANWERK_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PLANWERK.CONTROLLING TO ROLE PLANWERK_REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA PLANWERK.SEMANTIC    TO ROLE PLANWERK_REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA PLANWERK.FORECAST    TO ROLE PLANWERK_REPORTER;

-- Assistant: read semantic views only
GRANT USAGE ON SCHEMA PLANWERK.SEMANTIC TO ROLE PLANWERK_ASSISTANT;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA PLANWERK.SEMANTIC TO ROLE PLANWERK_ASSISTANT;

-- Service users: key pair only, no password -------------------------------------------------------
CREATE USER IF NOT EXISTS PLANWERK_CI TYPE = SERVICE
  DEFAULT_ROLE = PLANWERK_TRANSFORMER DEFAULT_WAREHOUSE = PLANWERK_WH
  COMMENT = 'Load S4_RAW and run dbt (GitHub Actions or a build session)';
ALTER USER PLANWERK_CI SET RSA_PUBLIC_KEY = '<PLANWERK_CI_PUBLIC_KEY>';
GRANT ROLE PLANWERK_LOADER      TO USER PLANWERK_CI;
GRANT ROLE PLANWERK_TRANSFORMER TO USER PLANWERK_CI;

CREATE USER IF NOT EXISTS PLANWERK_ASSISTANT TYPE = SERVICE
  DEFAULT_ROLE = PLANWERK_ASSISTANT DEFAULT_WAREHOUSE = PLANWERK_WH
  COMMENT = 'AI assistant: read-only on SEMANTIC';
ALTER USER PLANWERK_ASSISTANT SET RSA_PUBLIC_KEY = '<PLANWERK_ASSISTANT_PUBLIC_KEY>';
GRANT ROLE PLANWERK_ASSISTANT TO USER PLANWERK_ASSISTANT;

-- Last result row: the account identifier to send back (not a secret) --------------------------
SELECT CURRENT_ORGANIZATION_NAME() || '-' || CURRENT_ACCOUNT_NAME() AS ACCOUNT_IDENTIFIER,
       CURRENT_ACCOUNT() AS ACCOUNT_LOCATOR, CURRENT_REGION() AS REGION;
